#!/usr/bin/env python3
"""Turn data/chasers.txt (one card per line) into data/chasers.js for the Vault Packs page.

    python3 tools/build-chasers.py

Each line reads YEAR SET PLAYER INSERT GRADE, e.g.
    2024 DONRUSS OPTIC BROCK BOWERS DOWNTOWN PSA 9
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "chasers.txt"
OUT = ROOT / "data" / "chasers.js"

SETS = ["PANINI ABSOLUTE", "DONRUSS OPTIC", "TOPPS CHROME", "TOPPS COSMIC", "DONRUSS", "OPTIC", "MOSAIC",
        "PRIZM", "SELECT", "PHOENIX", "ABSOLUTE", "OBSIDIAN", "TOPPS", "ONE"]
GRADES = ["PSA 10", "PSA 9", "PSA 8", "BGS 9.5", "SGC 9", "NEAR MINT"]
# insert -> checklist group (longest inserts first so "DOWNTOWN DUOS" wins over "DOWNTOWN")
INSERTS = {
    "SUPER BOWL DOWNTOWN": "Downtowns", "DOWNTOWN DUOS": "Downtowns", "DOWNTOWN": "Downtowns",
    "UPTOWN": "Uptowns", "KABOOM": "Kabooms", "COLOR BLAST": "Color Blasts",
    "MICRO MOSAIC": "Micro Mosaics", "STAINED GLASS": "Stained Glass",
    "ULTRA VIOLET": "Topps Chrome & Cosmic", "HELIX": "Topps Chrome & Cosmic", "TECMO": "Topps Chrome & Cosmic",
    "SUN": "Topps Chrome & Cosmic", "JUPITER": "Topps Chrome & Cosmic",
    "ALTER EGO": "More case hits", "EXPLOSIVE": "More case hits", "PRIZMANIA": "More case hits",
    "GENESIS": "More case hits", "ZEBRA": "More case hits", "METAL MANGA": "More case hits",
}
ORDER = ["Downtowns", "Uptowns", "Kabooms", "Color Blasts", "Micro Mosaics", "Stained Glass",
         "Topps Chrome & Cosmic", "More case hits"]
UPPER = {"CJ", "JJ", "DK", "AJ", "II", "III", "NFL", "PSA", "BGS", "SGC"}
FIX = {"Mccarthy": "McCarthy", "Mcmillan": "McMillan", "Mclaurin": "McLaurin", "Laporta": "LaPorta",
       "Ja'marr": "Ja'Marr", "Ceedee": "CeeDee", "Jr": "Jr."}


def title(s):
    words = []
    for w in s.split():
        t = w if w.upper() in UPPER else w.capitalize()
        words.append(FIX.get(t, t))
    out = " ".join(words)
    return out.replace("Cj ", "CJ ").replace("Optic", "Optic")


def parse(line):
    s = line.upper().strip()
    year, rest = s.split(" ", 1)
    grade = next((g for g in GRADES if rest.endswith(" " + g)), "")
    if grade:
        rest = rest[: -len(grade) - 1]
    cset = next(x for x in SETS if rest.startswith(x + " "))
    rest = rest[len(cset) + 1:]
    insert = next(i for i in sorted(INSERTS, key=len, reverse=True) if rest.endswith(" " + i))
    player = rest[: -len(insert) - 1]
    card = f"{year} {title(cset)} {title(insert)}"
    return INSERTS[insert], {"name": title(player), "card": card, "note": "Near Mint" if grade == "NEAR MINT" else grade}


def main():
    seen, groups = set(), {g: [] for g in ORDER}
    for line in SRC.read_text(encoding="utf-8").splitlines():
        line = re.sub(r"\s+", " ", line).strip()
        if not line or line.startswith("#") or line.upper() in seen:
            continue
        seen.add(line.upper())
        group, item = parse(line)
        groups[group].append(item)
    for items in groups.values():
        items.sort(key=lambda i: (i["name"], i["card"]))
    data = [{"group": g, "items": groups[g]} for g in ORDER if groups[g]]
    OUT.write_text("/* Generated by tools/build-chasers.py from data/chasers.txt — do not edit by hand. */\n"
                   "window.CHASERS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(len(g['items']) for g in data)} cards in {len(data)} groups")


if __name__ == "__main__":
    main()
